import { expect, test } from '@playwright/test'

for (const viewport of [{ width: 320, height: 800 }, { width: 1280, height: 800 }]) {
  test(`guides a hidden leak from the pipe to reveal at ${viewport.width}px`, async ({ page, context }) => {
    test.setTimeout(60_000)
    await page.setViewportSize(viewport)
    await page.goto('/')
    const pipe = page.getByRole('region', { name: 'Модель участка' })
    const guide = pipe.getByRole('region', { name: 'Испытание на модели' })
    const canvas = page.getByTestId('pipe-3d-canvas')
    const revealAnchor = pipe.getByTestId('pipe-reveal-anchor')
    const slider = page.getByRole('slider', { name: 'Координата на 3D-модели' })
    await expect(guide).toBeVisible()
    await expect(guide.locator('form')).toHaveCount(0)
    await slider.press(viewport.width === 320 ? 'End' : 'ArrowRight')
    const selected = await slider.inputValue()
    await guide.getByRole('button', { name: 'Начать показ' }).click()
    await expect(page.getByRole('button', { name: '4×', exact: true })).toHaveAttribute('aria-pressed', 'true')
    const inject = page.getByRole('button', { name: 'Ввести утечку', exact: true })
    await expect(inject).toBeEnabled({ timeout: 30_000 })
    const formLink = guide.getByRole('link', { name: 'К форме утечки' })
    await expect(formLink).toHaveAttribute('href', '#leak-title')
    await formLink.click()
    await expect(page.getByRole('heading', { name: 'Скрытая утечка' })).toBeFocused()
    await expect(page.getByRole('spinbutton', { name: 'Координата', exact: true })).toHaveValue(selected)
    await context.setOffline(true)
    await inject.click()
    await expect(revealAnchor).toHaveCount(0)
    await expect(page.getByText('Скрытая утечка применена', { exact: true })).toBeVisible()
    await expect(canvas).toHaveAttribute('data-marker', 'hidden')
    await expect(pipe.locator('output')).toHaveCount(0)
    const diagnostic = page.getByRole('region', { name: 'Диагностика' })
    await expect(diagnostic.getByText(`${selected} м`, { exact: true })).toHaveCount(0)
    const readings = guide.locator('dl[aria-label="Отклонение давления после утечки"]')
    await expect(readings).toBeVisible({ timeout: 15_000 })
    await expect(readings).toContainText(/P[123]/)
    await expect(readings).toContainText(/[-+−]?\d+[,.]\d+ кПа/)
    await expect(guide.getByText(/По модели · \d{2}:\d{2}/)).toBeVisible()
    const residualLink = guide.getByRole('link', { name: 'Смотреть невязку' })
    await expect(residualLink).toHaveAttribute('href', '#trend-title')
    await residualLink.click()
    const telemetry = page.getByRole('region', { name: 'Телеметрия' })
    await expect(telemetry.getByRole('heading', { name: 'Телеметрия' })).toBeFocused()
    await expect(telemetry.getByRole('button', { name: 'Невязка', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(telemetry.getByRole('img')).toHaveAccessibleName(/Невязка по модельному времени/)
    const finishLink = telemetry.getByRole('link', { name: 'К раскрытию точки' })
    await expect(finishLink).toHaveAttribute('href', '#finish-title')
    await finishLink.click()
    await expect(page.getByRole('heading', { name: 'Итог испытания' })).toBeFocused()
    await page.getByRole('button', { name: 'Завершить и раскрыть' }).click()
    const reveal = diagnostic.getByRole('heading', { name: 'Раскрытое событие' })
    await expect(reveal).toBeFocused()
    await expect(diagnostic.getByText(`${selected} м`, { exact: true })).toBeVisible()
    const returnLink = diagnostic.getByRole('link', { name: 'Показать точку на трубе' })
    await expect(returnLink).toHaveAttribute('href', '#pipe-title')
    await pipe.getByRole('button', { name: 'Приблизить модель' }).click()
    await returnLink.click()
    await expect(pipe.getByRole('heading', { name: 'Модель участка' })).toBeFocused()
    await expect(pipe.getByRole('button', { name: 'Общий', exact: true })).toHaveAttribute('aria-pressed', 'true')
    await expect(canvas).toHaveAttribute('data-marker', 'revealed')
    await expect(guide.getByText(`${selected} м`, { exact: true })).toBeVisible()
    await expect(revealAnchor).toHaveText('Утечка')
  })
}
