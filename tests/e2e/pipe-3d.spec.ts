import { expect, test, type Page } from '@playwright/test'

async function startChallenge(page: Page) {
  const inject = page.getByRole('button', { name: 'Ввести утечку', exact: true })
  await expect(inject).toBeDisabled()
  await page.getByRole('button', { name: '4×', exact: true }).click()
  await page.getByRole('button', { name: 'Запустить сценарий', exact: true }).click()
  await expect(inject).toBeEnabled({ timeout: 30_000 })
  return inject
}

test('selects a location on the 3D pipe and runs the hidden leak offline', async ({ page, context }) => {
  test.setTimeout(50_000)
  const requests: string[] = []
  const pageErrors: string[] = []
  page.on('request', request => {
    const url = new URL(request.url())
    if (['http:', 'https:'].includes(url.protocol)) requests.push(url.href)
  })
  page.on('pageerror', error => pageErrors.push(error.message))

  await page.goto('/')
  const appOrigin = new URL(page.url()).origin
  const canvas = page.getByTestId('pipe-3d-canvas')
  await expect(canvas).toBeVisible()
  await expect(canvas).toHaveAttribute('data-marker', 'planned')
  const camera = page.getByRole('group', { name: 'Камера 3D-модели' })
  await camera.getByRole('button', { name: 'Приблизить модель' }).click()
  await camera.getByRole('button', { name: 'Восстановить вид' }).click()
  await expect(page.getByTestId('pipe-2d-fallback')).toBeHidden()
  const coordinate = page.getByRole('spinbutton', { name: 'Координата', exact: true })
  await expect(coordinate).toHaveValue('500')
  await expect(coordinate).toBeDisabled()

  const beforeRotation = await canvas.screenshot()
  const box = await canvas.boundingBox()
  expect(box).not.toBeNull()
  const grabX = box!.x + box!.width * 0.5
  const grabY = box!.y + box!.height * 0.5
  await page.mouse.move(grabX, grabY)
  await page.mouse.down()
  await page.mouse.move(grabX + 55, grabY - 18, { steps: 5 })
  await page.mouse.up()
  await expect(coordinate).toHaveValue('500')
  await expect.poll(() => canvas.screenshot()).not.toEqual(beforeRotation)
  await camera.getByRole('button', { name: 'Восстановить вид' }).click()
  await expect(coordinate).toHaveValue('500')
  await canvas.click({ position: { x: box!.width * 0.66, y: box!.height * 0.48 } })
  await expect(coordinate).not.toHaveValue('500')
  const preview = Number(await coordinate.inputValue())
  expect(preview).toBeGreaterThan(500)
  expect(preview).toBeLessThanOrEqual(995)
  expect(preview % 5).toBe(0)

  const slider = page.getByRole('slider', { name: 'Координата на 3D-модели' })
  await slider.press('ArrowRight')
  await expect(coordinate).toHaveValue(String(preview + 5))

  const inject = page.getByRole('button', { name: 'Ввести утечку', exact: true })
  await page.getByRole('button', { name: 'Запустить сценарий', exact: true }).click()
  await expect(page.getByRole('status').filter({ hasText: 'Штатный разогрев' })).toBeVisible()
  await expect(inject).toBeDisabled()
  await expect(canvas).toHaveAttribute('data-marker', 'planned', { timeout: 1_000 })
  await expect(slider).toHaveValue(String(preview + 5))
  await slider.press('ArrowRight')
  await expect(coordinate).toHaveValue(String(preview + 10))
  await page.getByRole('button', { name: '4×', exact: true }).click()
  await expect(inject).toBeEnabled({ timeout: 30_000 })
  await expect(coordinate).toHaveValue(String(preview + 10))
  await canvas.click({ position: { x: box!.width * 0.44, y: box!.height * 0.50 } })
  await expect(coordinate).not.toHaveValue(String(preview + 10))
  const selected = Number(await coordinate.inputValue())
  expect(selected).toBeGreaterThanOrEqual(5)
  expect(selected).toBeLessThan(500)
  expect(selected % 5).toBe(0)
  await coordinate.fill('502')
  await expect(coordinate).toHaveValue('502')
  await expect(slider).toHaveValue(String(selected), { timeout: 1_500 })
  await expect(coordinate).toHaveAttribute('aria-invalid', 'true')
  await expect(coordinate).toHaveAccessibleDescription('Введите координату от 5 до 995 м с шагом 5 м.')
  await slider.press('ArrowRight')
  await expect(coordinate).toHaveValue(String(selected + 5))
  await expect(coordinate).not.toHaveAttribute('aria-invalid', 'true')
  await expect(page.getByText('Введите координату от 5 до 995 м с шагом 5 м.', { exact: true })).toHaveCount(0)
  expect(page.workers().some(worker => new URL(worker.url()).pathname.includes('simulation.worker-'))).toBe(true)
  await context.setOffline(true)
  await inject.click()
  await expect(page.getByText('Скрытая утечка применена', { exact: true })).toBeVisible()
  await expect(page.getByRole('status').filter({ hasText: 'Скрытый отбор запланирован.' })).toHaveCount(0, { timeout: 1_500 })
  await expect(coordinate).toHaveCount(0)
  await expect(slider).toHaveCount(0)
  await expect(canvas).toHaveAttribute('data-marker', 'hidden')
  const telemetry = page.getByRole('region', { name: 'Телеметрия', exact: true })
  const residualView = telemetry.getByRole('button', { name: 'Невязка', exact: true })
  await expect(residualView).toHaveAttribute('aria-pressed', 'false')
  const residualLink = page.getByRole('region', { name: 'Скрытая утечка' })
    .getByRole('link', { name: 'Смотреть невязку', exact: true })
  await expect(residualLink).toBeVisible({ timeout: 2_000 })
  await residualLink.press('Enter')
  const telemetryHeading = telemetry.getByRole('heading', { name: 'Телеметрия', exact: true })
  await expect(telemetryHeading).toBeFocused()
  await expect(telemetryHeading).toBeInViewport()
  await expect(residualView).toHaveAttribute('aria-pressed', 'true')
  await expect(telemetry.getByRole('img')).toHaveAccessibleName(/Невязка по модельному времени/)
  const diagnostic = page.getByRole('region', { name: 'Диагностика', exact: true })
  const reveal = diagnostic.getByRole('heading', { name: 'Раскрытое событие', exact: true })
  await expect(reveal).toHaveCount(0)
  const residual = page.getByRole('row', { name: /^P2 / }).getByRole('cell').last()
  await expect.poll(async () => {
    const value = (await residual.innerText()).replace(/\s/g, '').replace('−', '-').replace(',', '.')
    return Math.abs(Number.parseFloat(value))
  }).toBeGreaterThan(0.7)
  await page.getByRole('button', { name: 'Завершить и раскрыть' }).click()
  await expect(reveal).toBeVisible()
  await expect(canvas).toHaveAttribute('data-marker', 'revealed')
  await expect(diagnostic.getByText(`${selected + 5} м`, { exact: true })).toBeVisible()

  expect(requests.filter(url => new URL(url).origin !== appOrigin)).toEqual([])
  expect(pageErrors).toEqual([])
})

test('keeps the 2D diagram and numeric location usable when WebGL is unavailable', async ({ page }) => {
  test.setTimeout(50_000)
  await page.addInitScript(() => {
    const getContext = HTMLCanvasElement.prototype.getContext
    Object.defineProperty(HTMLCanvasElement.prototype, 'getContext', {
      value(...args: Parameters<typeof getContext>) {
        return String(args[0]).includes('webgl') ? null : Reflect.apply(getContext, this, args)
      },
    })
  })

  await page.goto('/')
  await expect(page.getByTestId('pipe-2d-fallback')).toBeVisible()
  const inject = await startChallenge(page)
  const coordinate = page.getByRole('spinbutton', { name: 'Координата', exact: true })
  const slider = page.getByRole('slider', { name: 'Координата на схеме' })
  await coordinate.fill('356')
  await expect(coordinate).toHaveAttribute('aria-invalid', 'true', { timeout: 1_500 })
  await expect(coordinate).toHaveAccessibleDescription('Введите координату от 5 до 995 м с шагом 5 м.')
  await expect(slider).toHaveValue('500')
  await coordinate.press('Enter')
  await expect(page.getByText('Скрытая утечка применена', { exact: true })).toHaveCount(0)
  await coordinate.fill('355')
  await expect(coordinate).toHaveValue('355')
  await expect(slider).toHaveValue('355')
  await expect(coordinate).not.toHaveAttribute('aria-invalid', 'true')
  await expect(inject).toBeEnabled()
  await inject.click()
  await expect(page.getByText('Скрытая утечка применена', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Завершить и раскрыть' }).click()
  await expect(page.getByRole('region', { name: 'Диагностика', exact: true })
    .getByText('355 м', { exact: true })).toBeVisible()
})
